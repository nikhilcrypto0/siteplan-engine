"""Acceptance on the production search (2026-10-18): `siteplan acceptance` runs the raw survey and
the answers through the service's full search with the readings the project selects, every layout
judged by the independent validator, and compares the best with the firm's plan only afterwards,
both measured the same way. Made-up land: test_acceptance.py's 150 x 120 m plot."""

import json
import re

import pytest
from test_acceptance import ANSWERS, _firm_case, _workspace

from siteplan import acceptance_full
from siteplan.acceptance import spacing
from siteplan.blind import BlindLeak
from siteplan.cli import main
from siteplan.optimizer.search.verdicts import rests_on

TEST_CLASS = "normative"

READINGS = {"stilt_in_rule_height": {"reading": "not_counted", "status": "USER_CONFIRMED",
                                     "source": "the architect, 2026-10-11"},
            "circulation_in_setback": {"reading": "allowed", "status": "USER_CONFIRMED",
                                       "source": "the architect, 2026-10-13"}}


@pytest.fixture(scope="module")
def run(tmp_path_factory):
    ws = _workspace(tmp_path_factory.mktemp("ws"))
    return acceptance_full.generate(ws / "survey.dxf", {**ANSWERS, "readings": READINGS},
                                    ws / "out")


def test_the_layouts_come_from_the_full_search_built_for_the_projects_readings(run):
    assert acceptance_full.proposed(run)
    record = json.loads(next((run.out / "runs").glob("*/run.json")).read_text())
    assert record["mode"] == "BLIND"
    laid_for = {(c["basis"]["stilt_in_rule_height"], c["basis"]["circulation_in_setback"])
                for c in record["proposed_candidates"]}
    assert laid_for == {("not_counted", "allowed")}
    for candidate, report in run.shown:
        assert candidate.candidate_id.startswith("full-")
        assert report.verdict.legal.value != "FAIL"
    assert record["approvals"][0]["channel"] == "AcceptanceCommand"


def test_the_report_says_how_it_was_generated_and_names_what_each_verdict_rests_on(run):
    text = acceptance_full.report(run, acceptance_full.compare(run, _firm_case()))
    assert text.startswith("ACCEPTANCE")
    assert "Generated by the service's full search with the readings the project selects" in text
    assert ("Readings the project selects: stilt_in_rule_height = not_counted, "
            "circulation_in_setback = allowed") in text
    for heading in ("1. EXTRACTED FROM THE SURVEY", "2. INPUTS AND HOW FAR EACH IS TRUSTED",
                    "3. UNRESOLVED FACTS AND ASSUMPTIONS", "4. HEIGHT", "5. LAYOUTS SHOWN",
                    "6. THE SEARCH'S NOTES", "7. COMPARED WITH THE FIRM'S PLAN (read only now)"):
        assert heading in text, heading
    for candidate, report in run.shown:
        assert candidate.candidate_id in text
        for reading in rests_on(report).readings:
            assert reading in text
    # 2026-10-19: every tower's way in from the gate, with its length
    assert re.search(r"T1: .*; route: [\d,]+ m from the gate", text)


def test_the_best_is_compared_with_the_firms_plan_measured_the_same_way(run):
    rows = dict((name, (ours, theirs))
                for name, ours, theirs in acceptance_full.compare(run, _firm_case()))
    candidate, _ = run.best
    setback, gap = spacing(run.net, [candidate.placed_footprint(t) for t in candidate.towers])
    assert rows["Least setback from the plot line"][0] == f"{setback:.2f} m"
    assert rows["Least setback from the plot line"][1] == "8.00 m"  # the made-up firm's 8 m
    assert rows["Least gap between towers"][1] == "8.00 m"
    assert rows["Flats"][0] == str(candidate.metrics.total_flats)
    assert rows["Verdict (the independent validator)"][0].startswith(
        run.best[1].verdict.legal.value)


def test_a_blind_run_refuses_the_firms_finished_plan(tmp_path):
    ws = _workspace(tmp_path)
    leaked = {**ANSWERS, "_source_kind": {"surrender": "FIRM_FINISHED_PLAN"}}
    with pytest.raises(BlindLeak):
        acceptance_full.generate(ws / "survey.dxf", leaked, ws / "out")


def test_the_acceptance_command_runs_the_full_search(run, tmp_path, monkeypatch, capsys):
    answers, case = tmp_path / "answers.json", tmp_path / "firm.case.json"
    answers.write_text(json.dumps(ANSWERS))
    case.write_text(_firm_case().model_dump_json())
    monkeypatch.setattr(acceptance_full, "generate", lambda *args, **kwargs: run)
    assert main(["acceptance", str(tmp_path / "survey.dxf"), "--answers", str(answers),
                 "--firm-case", str(case), "--out", str(run.out)]) == 0
    assert "Generated by the service's full search" in capsys.readouterr().out
    assert "7. COMPARED WITH THE FIRM'S PLAN" in (run.out / "acceptance.txt").read_text()
